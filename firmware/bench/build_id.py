# bench/build_id.py — PlatformIO pre: extra script (build-id contract, see bench/README.md).
# Writes <project>/src/build_id.h with  #define BUILD_ID "<env BUILD_ID or 'dev'>"
# only when the id changed, so a new id recompiles just the files that include it (seconds),
# instead of a full ESP-IDF rebuild (~65 s) that a changing -D build flag triggers.
import os
Import("env")  # noqa: F821  (provided by PlatformIO/SCons)
bid = os.environ.get("BUILD_ID") or "dev"
path = os.path.join(env.subst("$PROJECT_SRC_DIR"), "build_id.h")  # noqa: F821
text = '#pragma once\n// generated by bench/build_id.py — do not edit, do not commit\n#define BUILD_ID "%s"\n' % bid.replace('"', "")
try:
    old = open(path).read()
except OSError:
    old = None
if old != text:
    with open(path, "w") as f:
        f.write(text)
print("bench/build_id.py: BUILD_ID=%s" % bid)
